// 每日报告分享卡：用 Canvas 绘制 1080×1440 PNG，不依赖远程资源。

import type { DailyReport } from "./types";

function numberStat(report: DailyReport, key: string): number {
  const value = report.stats[key];
  return typeof value === "number" && Number.isFinite(value) ? Math.round(value) : 0;
}

function formatDuration(secs: number): string {
  const min = Math.max(0, Math.round(secs / 60));
  if (min < 60) return `${min} 分钟`;
  return `${Math.floor(min / 60)} 小时 ${min % 60} 分`;
}

function wrapText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  maxWidth: number,
  lineHeight: number,
  maxLines: number,
): number {
  const chars = Array.from(text || "");
  let line = "";
  let lines = 0;
  for (const ch of chars) {
    const test = line + ch;
    if (ctx.measureText(test).width > maxWidth && line) {
      ctx.fillText(line, x, y);
      line = ch;
      y += lineHeight;
      lines += 1;
      if (lines >= maxLines) return y;
    } else {
      line = test;
    }
  }
  if (line) {
    ctx.fillText(line, x, y);
    y += lineHeight;
  }
  return y;
}

function roundedRect(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  width: number,
  height: number,
  radius: number,
) {
  ctx.beginPath();
  ctx.roundRect(x, y, width, height, radius);
  ctx.fill();
}

export function renderReportCard(report: DailyReport, name: string): string {
  const canvas = document.createElement("canvas");
  canvas.width = 1080;
  canvas.height = 1440;
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("无法创建分享卡画布");

  const root = document.querySelector(".dsh-vpet-root") as HTMLElement | null;
  const style = root ? getComputedStyle(root) : null;
  const accent = (style?.getPropertyValue("--pink").trim() || "#ff5d8f") as string;
  const mint = (style?.getPropertyValue("--mint").trim() || "#1fc4a4") as string;
  const ink = (style?.getPropertyValue("--ink").trim() || "#3d3146") as string;

  const bg = ctx.createLinearGradient(0, 0, 1080, 1440);
  bg.addColorStop(0, "#fff8fb");
  bg.addColorStop(0.55, "#fffdf9");
  bg.addColorStop(1, "#f4fffb");
  ctx.fillStyle = bg;
  ctx.fillRect(0, 0, 1080, 1440);

  ctx.fillStyle = accent;
  ctx.globalAlpha = 0.1;
  ctx.beginPath();
  ctx.arc(920, 130, 230, 0, Math.PI * 2);
  ctx.fill();
  ctx.beginPath();
  ctx.arc(130, 1260, 270, 0, Math.PI * 2);
  ctx.fill();
  ctx.globalAlpha = 1;

  ctx.fillStyle = accent;
  roundedRect(ctx, 72, 92, 132, 48, 24);
  ctx.fillStyle = "#fff";
  ctx.font = "700 24px 'Microsoft YaHei', sans-serif";
  ctx.fillText("DSH PET", 100, 124);

  ctx.fillStyle = ink;
  ctx.font = "800 70px 'Microsoft YaHei', sans-serif";
  ctx.fillText("每日陪伴报告", 72, 238);
  ctx.fillStyle = "#897d91";
  ctx.font = "500 30px 'Microsoft YaHei', sans-serif";
  ctx.fillText(`${name ? `「${name}」` : "桌宠"} · ${report.date}`, 76, 292);

  ctx.fillStyle = "#fff";
  roundedRect(ctx, 72, 352, 936, 196, 32);
  ctx.fillStyle = accent;
  ctx.font = "800 54px 'Microsoft YaHei', sans-serif";
  ctx.fillText(formatDuration(report.companionSecs), 112, 442);
  ctx.fillStyle = "#897d91";
  ctx.font = "500 26px 'Microsoft YaHei', sans-serif";
  ctx.fillText("今天陪在你身边的时间", 114, 486);
  ctx.fillStyle = mint;
  ctx.font = "800 36px 'Microsoft YaHei', sans-serif";
  ctx.fillText(`${numberStat(report, "chat")} 次聊天`, 704, 424);
  ctx.fillText(`${numberStat(report, "focusMin")} 分钟专注`, 704, 478);

  ctx.fillStyle = "#fff";
  roundedRect(ctx, 72, 588, 936, 604, 34);

  let y = 656;
  const sections: [string, string][] = [
    ["💬 今天聊了什么", report.chatSummary],
    ["✅ 完成了什么", report.doneSummary],
    ["🌤 明天的小建议", report.tomorrow],
  ];
  for (const [title, body] of sections) {
    ctx.fillStyle = accent;
    ctx.font = "800 30px 'Microsoft YaHei', sans-serif";
    ctx.fillText(title, 112, y);
    y += 46;
    ctx.fillStyle = ink;
    ctx.font = "500 27px 'Microsoft YaHei', sans-serif";
    y = wrapText(ctx, body || "（今天没有记录）", 112, y, 850, 42, 4) + 24;
  }

  ctx.fillStyle = "#fff";
  roundedRect(ctx, 72, 1230, 936, 120, 28);
  ctx.fillStyle = ink;
  ctx.font = "600 28px 'Microsoft YaHei', sans-serif";
  wrapText(ctx, report.mood || "哼，今天也算勉强陪你一下吧。", 112, 1284, 850, 38, 2);
  ctx.fillStyle = "#a59aa9";
  ctx.font = "500 22px 'Microsoft YaHei', sans-serif";
  ctx.fillText("Generated by DSH Pet", 76, 1396);

  return canvas.toDataURL("image/png");
}
